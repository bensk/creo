import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { serverEnv } from "../env";

// Private file storage. Objects are never public: the app reads them after its
// own permission check and streams them back. Production uses the Cloud Storage
// bucket named by FILES_BUCKET; development and tests use data/files (gitignored).

export interface StoredObject {
  body: Buffer;
  contentType: string;
}

export interface FileStore {
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<StoredObject | null>;
  remove(key: string): Promise<void>;
}

const KEY = /^[a-z0-9][a-z0-9/_.-]{0,250}$/;

/** Object keys are generated by the app (never from user input) and must stay inside the store. */
export function assertKey(key: string): void {
  if (!KEY.test(key) || key.includes("..") || key.includes("//")) throw new Error("Invalid object key");
}

function localStore(root: string): FileStore {
  const full = (key: string) => {
    assertKey(key);
    return path.join(root, key);
  };
  return {
    async put(key, body, contentType) {
      const file = full(key);
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, body);
      await writeFile(`${file}.type`, contentType);
    },
    async get(key) {
      const file = full(key);
      try {
        const [body, type] = await Promise.all([readFile(file), readFile(`${file}.type`, "utf8")]);
        return { body, contentType: type };
      } catch {
        return null;
      }
    },
    async remove(key) {
      const file = full(key);
      await rm(file, { force: true });
      await rm(`${file}.type`, { force: true });
    },
  };
}

async function bucketStore(bucketName: string): Promise<FileStore> {
  const { Storage } = await import("@google-cloud/storage");
  const bucket = new Storage().bucket(bucketName);
  return {
    async put(key, body, contentType) {
      assertKey(key);
      await bucket.file(key).save(body, { contentType, resumable: false });
    },
    async get(key) {
      assertKey(key);
      const file = bucket.file(key);
      try {
        const [[body], [meta]] = await Promise.all([file.download(), file.getMetadata()]);
        return { body, contentType: meta.contentType ?? "application/octet-stream" };
      } catch (error) {
        if ((error as { code?: number }).code === 404) return null;
        throw error;
      }
    },
    async remove(key) {
      assertKey(key);
      await bucket.file(key).delete({ ignoreNotFound: true });
    },
  };
}

let store: Promise<FileStore> | undefined;

export function fileStore(): Promise<FileStore> {
  if (!store) {
    const env = serverEnv();
    if (env.FILES_BUCKET) store = bucketStore(env.FILES_BUCKET);
    else if (env.NODE_ENV === "production") throw new Error("FILES_BUCKET must be set in production");
    else store = Promise.resolve(localStore(path.join(process.cwd(), "data", "files", env.NODE_ENV)));
  }
  return store;
}
